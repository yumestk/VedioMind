CREATE TABLE study_artifacts (
 id VARCHAR(36) PRIMARY KEY,
 run_id VARCHAR(36) NOT NULL,
 learner_id BIGINT NOT NULL,
 slot_id VARCHAR(100) NOT NULL,
 kind VARCHAR(20) NOT NULL,
 operation_id VARCHAR(160) NOT NULL,
 payload_fingerprint CHAR(64) NOT NULL,
 base_version BIGINT NOT NULL,
 version BIGINT NOT NULL DEFAULT 1,
 status VARCHAR(20) NOT NULL DEFAULT 'CANDIDATE',
 content_json JSON NOT NULL,
 citations_json JSON NOT NULL,
 coverage_json JSON NOT NULL,
 edited BOOLEAN NOT NULL DEFAULT FALSE,
 created_at DATETIME(3) NOT NULL,
 updated_at DATETIME(3) NOT NULL,
 UNIQUE KEY uk_artifact_operation(operation_id),
 UNIQUE KEY uk_artifact_slot(run_id,slot_id),
 INDEX idx_artifact_learner(learner_id,status,updated_at),
 CONSTRAINT ck_artifact_kind CHECK(kind='NOTE'),
 CONSTRAINT ck_artifact_status CHECK(status IN ('CANDIDATE','DELIVERED')),
 CONSTRAINT fk_artifact_run FOREIGN KEY(run_id) REFERENCES video_agent_runs(id) ON DELETE RESTRICT,
 CONSTRAINT fk_artifact_learner FOREIGN KEY(learner_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
